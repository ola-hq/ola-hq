-- Public feedback is served only through cinema-community. Browser roles cannot access raw rows.
create table public.cinema_feedback_films (id text primary key);
alter table public.cinema_feedback_films enable row level security;
revoke all on public.cinema_feedback_films from public, anon, authenticated;
grant select on public.cinema_feedback_films to service_role;
create table public.cinema_film_feedback (
 id uuid primary key default gen_random_uuid(),
 film_id text not null references public.cinema_feedback_films(id),
 voter_hash text not null check(voter_hash ~ '^[a-f0-9]{64}$'),
 source_hash text not null check(source_hash ~ '^[a-f0-9]{64}$'),
 reaction smallint check(reaction in (-1,1)),
 display_name text not null default '' check(char_length(display_name)<=40),
 review_text text check(char_length(review_text) between 10 and 1600),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 reviewed_at timestamptz,
 unique(film_id,voter_hash)
);
alter table public.cinema_film_feedback enable row level security;
revoke all on public.cinema_film_feedback from public, anon, authenticated;
grant select,insert,update,delete on public.cinema_film_feedback to service_role;
create index cinema_feedback_source_created on public.cinema_film_feedback(source_hash,created_at);
create index cinema_feedback_public_reviews on public.cinema_film_feedback(film_id,reviewed_at desc,id) where review_text is not null;
create function public.cinema_film_summary(p_film text,p_voter text default null,p_offset integer default 0)
returns jsonb language sql stable security invoker set search_path='' as $$
 select jsonb_build_object(
  'likes',count(*) filter(where reaction=1), 'dislikes',count(*) filter(where reaction=-1),
  'reviewCount',count(*) filter(where review_text is not null),
  'reviews',coalesce((select jsonb_agg(x order by x.reviewed_at desc,x.id) from
   (select id,display_name as name,review_text as review,reviewed_at from public.cinema_film_feedback where film_id=p_film and review_text is not null order by reviewed_at desc,id offset greatest(0,least(p_offset,10000)) limit 20) x),'[]'::jsonb),
  'mine',(select jsonb_build_object('reaction',reaction,'name',display_name,'review',review_text) from public.cinema_film_feedback where film_id=p_film and voter_hash=p_voter)
 ) from public.cinema_film_feedback where film_id=p_film;
$$;
revoke all on function public.cinema_film_summary(text,text,integer) from public,anon,authenticated;
grant execute on function public.cinema_film_summary(text,text,integer) to service_role;
create function public.cinema_film_respond(p_film text,p_voter text,p_source text,p_action text,p_reaction smallint default null,p_name text default '',p_review text default null)
returns jsonb language plpgsql security invoker set search_path='' as $$
declare old public.cinema_film_feedback;
begin
 if not exists(select 1 from public.cinema_feedback_films where id=p_film) or p_voter !~ '^[a-f0-9]{64}$' or p_source !~ '^[a-f0-9]{64}$' or p_action not in ('react','review','remove_review') then raise exception 'INVALID_INPUT'; end if;
 if p_action='react' and p_reaction is not null and p_reaction not in (-1,1) then raise exception 'INVALID_INPUT'; end if;
 if p_action='review' and (p_review is null or char_length(trim(p_review)) not between 10 and 1600 or char_length(p_name)>40) then raise exception 'INVALID_INPUT'; end if;
 perform pg_advisory_xact_lock(hashtextextended('cinema-feedback-source:'||p_source,0));
 perform pg_advisory_xact_lock(hashtextextended('cinema-feedback:'||p_film||p_voter,0));
 select * into old from public.cinema_film_feedback where film_id=p_film and voter_hash=p_voter;
 if old.updated_at>now()-interval '1 second' then raise exception 'SLOW_DOWN'; end if;
 if old.id is null and (select count(*) from public.cinema_film_feedback where source_hash=p_source and created_at>now()-interval '1 day')>=30 then raise exception 'RATE_LIMIT'; end if;
 insert into public.cinema_film_feedback(film_id,voter_hash,source_hash) values(p_film,p_voter,p_source) on conflict(film_id,voter_hash) do nothing;
 if p_action='react' then update public.cinema_film_feedback set reaction=p_reaction,source_hash=p_source,updated_at=now() where film_id=p_film and voter_hash=p_voter;
 elsif p_action='review' then update public.cinema_film_feedback set display_name=trim(p_name),review_text=trim(p_review),reviewed_at=now(),source_hash=p_source,updated_at=now() where film_id=p_film and voter_hash=p_voter;
 else update public.cinema_film_feedback set display_name='',review_text=null,reviewed_at=null,updated_at=now() where film_id=p_film and voter_hash=p_voter;
 end if;
 return public.cinema_film_summary(p_film,p_voter,0);
end;
$$;
revoke all on function public.cinema_film_respond(text,text,text,text,smallint,text,text) from public,anon,authenticated;
grant execute on function public.cinema_film_respond(text,text,text,text,smallint,text,text) to service_role;

