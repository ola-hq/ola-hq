import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

export const sourcePath = 'scripts/content/festival-updates.json';
export const publicPath = 'la-ola-de-amor/scan/guide/festival-updates.js';
export const MAX_CURRENT = 2;

// Publication dates are retained. Same-date entries use ascending immutable ID.
export function reconcileAnnouncements(entries) {
  const ids = new Set();
  for (const entry of entries) {
    if (!/^[a-z0-9-]+$/.test(entry.id) || ids.has(entry.id)) throw new Error('Invalid or duplicate announcement ID');
    ids.add(entry.id);
    if (!['current', 'archived'].includes(entry.status)) throw new Error('Invalid publication status');
    if (!/^\d{4}-\d{2}-\d{2}$/.test(entry.publishedAt) || !Number.isFinite(Date.parse(entry.publishedAt + 'T12:00:00Z')) || new Date(entry.publishedAt + 'T12:00:00Z').toISOString().slice(0, 10) !== entry.publishedAt) throw new Error('Invalid publication date');
    for (const key of ['title', 'body', 'audience']) {
      if (!['en', 'es'].every(lang => typeof entry[key]?.[lang] === 'string' && entry[key][lang].trim())) throw new Error('Both languages are required: ' + key);
    }
    if (!['confirmed', 'pending'].includes(entry.priority) || typeof entry.revision !== 'string' || !entry.revision) throw new Error('Invalid announcement metadata');
    if (!['updates', 'today', 'music', 'plaza', 'food', 'tornaboda'].includes(entry.route)) throw new Error('Invalid announcement route');
  }
  const newest = entries.filter(entry => entry.status === 'current').sort((a, b) => b.publishedAt.localeCompare(a.publishedAt) || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const retained = new Set(newest.slice(0, MAX_CURRENT).map(entry => entry.id));
  return entries.map(entry => entry.status === 'current' && !retained.has(entry.id) ? {...entry, status: 'archived'} : {...entry});
}

export function currentAnnouncements(entries) {
  return reconcileAnnouncements(entries).filter(entry => entry.status === 'current').sort((a, b) => b.publishedAt.localeCompare(a.publishedAt) || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
}

export function restoreAnnouncement(entries, id) {
  if (!entries.some(entry => entry.id === id)) throw new Error('Unknown announcement: ' + id);
  const restored = reconcileAnnouncements(entries.map(entry => entry.id === id ? {...entry, status: 'current'} : entry));
  if (restored.find(entry => entry.id === id).status !== 'current') throw new Error('Two newer announcements occupy the feed; archive one before restoring this entry');
  return restored;
}

export function publicScript(entries) {
  // Internal publication state, provenance and archived copy never reach the guest artifact.
  const visible = currentAnnouncements(entries).map(({id, revision, publishedAt, priority, audience, title, body, route}) => ({id, revision, publishedAt, priority, audience, title, body, route}));
  return "'use strict';\n// Generated by scripts/festival-updates.mjs. Edit scripts/content/festival-updates.json.\nconst FESTIVAL_UPDATES = " + JSON.stringify(visible, null, 2) + ';\n';
}

export function syncAnnouncements(root = '.', {check = false, restore} = {}) {
  const sourceFile = resolve(root, sourcePath), publicFile = resolve(root, publicPath);
  const sourceText = readFileSync(sourceFile, 'utf8');
  const source = JSON.parse(sourceText);
  if (source.schema !== 1 || !Array.isArray(source.announcements)) throw new Error('Unsupported announcement source');
  const entries = restore ? restoreAnnouncement(source.announcements, restore) : reconcileAnnouncements(source.announcements);
  const nextSource = JSON.stringify({...source, announcements: entries}, null, 2) + '\n';
  const nextPublic = publicScript(entries);
  if (check) {
    if (nextSource !== sourceText || readFileSync(publicFile, 'utf8') !== nextPublic) throw new Error('Announcement source/feed is stale; run node scripts/festival-updates.mjs and commit both files');
  } else {
    writeFileSync(sourceFile, nextSource);
    writeFileSync(publicFile, nextPublic);
  }
  return entries;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const args = process.argv.slice(2);
  if (args.some(arg => arg !== '--check' && !arg.startsWith('--restore=')) || (args.includes('--check') && args.some(arg => arg.startsWith('--restore=')))) throw new Error('Usage: node scripts/festival-updates.mjs [--check | --restore=ID]');
  const entries = syncAnnouncements('.', {check: args.includes('--check'), restore: args.find(arg => arg.startsWith('--restore='))?.slice(10)});
  console.log(`Festival Updates: ${entries.filter(entry => entry.status === 'current').length} current; ${entries.filter(entry => entry.status === 'archived').length} archived. ${args.includes('--check') ? 'Verified.' : 'Source and guest feed synchronized.'}`);
}
